#!/usr/bin/env python3
"""Generate the /usage price table from plugin.js (the clients' canonical source).

Why this exists: /usage must not fork the price table. The desktop plugin owns
PRICES / PRICES_OPENROUTER / PRICES_NOUS, and a second hardcoded copy drifts
silently — the first draft of /usage shipped a mistral-large-latest price 4x
the real one that way.

The CLI plugin therefore needs the table in a form it can read without parsing
JavaScript at runtime, and WITHOUT depending on plugin.js being present (a pure
CLI install has no desktop plugin). So: parse the JS literals here, at build /
install time, and emit prices.json next to the plugin.

Usage:
    python3 scripts/gen_prices_usage.py            # writes into plugin_pkg/usage/
    python3 scripts/gen_prices_usage.py --check    # exit 1 if out of date
"""
from __future__ import annotations

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
PLUGIN_JS = os.path.join(REPO, "plugin.js")
OUT = os.path.join(REPO, "backend", "plugin_pkg", "usage", "prices.json")

ROW = re.compile(
    r"'([^']+)'\s*:\s*\{\s*input:\s*(-?[\d.]+)\s*,\s*"
    r"cached:\s*(-?[\d.]+)\s*,\s*output:\s*(-?[\d.]+)\s*\}"
)

# const EUR_RATE = 0.85  — the USD→EUR list-price factor the clients use.
# Shipped alongside the tables so the CLI mirrors EUR from the ONE canonical
# constant instead of hardcoding a second rate that silently drifts.
EUR_RATE = re.compile(r"const\s+EUR_RATE\s*=\s*(-?[\d.]+)")


def eur_rate(src: str) -> float:
    m = EUR_RATE.search(src)
    return float(m.group(1)) if m else 0.85


def block(src: str, const: str) -> dict:
    """Extract `const <const> = { ... }` as {key: [in, cached, out]}."""
    start = src.find("const " + const + " = {")
    if start < 0:
        return {}
    end = src.find("\n}", start)
    if end < 0:
        return {}
    out = {}
    for m in ROW.finditer(src[start:end]):
        try:
            out[m.group(1)] = [
                float(m.group(2)), float(m.group(3)), float(m.group(4)),
            ]
        except ValueError:
            continue
    return out


def build() -> dict:
    with open(PLUGIN_JS, encoding="utf-8") as fh:
        src = fh.read()

    model = block(src, "PRICES")
    openrouter = block(src, "PRICES_OPENROUTER")
    nous = block(src, "PRICES_NOUS")

    # The client aliases PRICES_PROVIDER.nous = PRICES_OPENROUTER when no
    # dedicated Nous table exists (plugin.js comment: same source, separately
    # maintained). Mirror that alias so Nous rows price like the UI does.
    if not nous:
        nous = dict(openrouter)

    if not model:
        sys.exit("error: could not parse PRICES out of plugin.js — "
                 "did the table format change?")

    return {
        "_comment": "Generated by scripts/gen_prices_usage.py from plugin.js — "
                    "do not edit by hand.",
        "eur_rate": eur_rate(src),
        "model": model,
        "provider": {"openrouter": openrouter, "nous": nous},
    }


def main() -> int:
    data = build()
    check = "--check" in sys.argv

    if check:
        try:
            with open(OUT, encoding="utf-8") as fh:
                if json.load(fh) == data:
                    print(f"ok: {OUT} is current")
                    return 0
        except (OSError, ValueError):
            pass
        print(f"STALE: {OUT} is out of date — run scripts/gen_prices_usage.py")
        return 1

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    # Compact, sorted, stable: this is a generated data file, not something
    # anyone reads line-by-line. Key-sorted so regeneration is a no-op diff.
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(data, fh, sort_keys=True, separators=(",", ":"))
        fh.write("\n")
    print(f"wrote {OUT}: {len(data['model'])} models, "
          f"{len(data['provider']['openrouter'])} openrouter, "
          f"{len(data['provider']['nous'])} nous")
    return 0


if __name__ == "__main__":
    sys.exit(main())
